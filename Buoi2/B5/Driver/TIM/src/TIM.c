#include "TIM.h"
#include "GPIO.h"

void TIM2_PWM_Init(void)
{

    // =====================================================
    // Timer frequency
    //
    // 72 MHz / (71 + 1)
    // = 1 MHz
    // =====================================================

    TIM2->PSC = 71;

    // 1 MHz / 1000 = 1 kHz PWM
    TIM2->ARR = 999;


    // =====================================================
    // Clear PWM configuration
    // =====================================================

    TIM2->CCMR1 = 0;
    TIM2->CCMR2 = 0;


    // =====================================================
    // CH1 - PWM Mode 1
    // OC1M = 110
    // OC1PE = 1
    // =====================================================

    TIM2->CCMR1 |= (6 << 4);
    TIM2->CCMR1 |= (1 << 3);


    // =====================================================
    // CH2 - PWM Mode 1
    // =====================================================

    TIM2->CCMR1 |= (6 << 12);
    TIM2->CCMR1 |= (1 << 11);


    // =====================================================
    // CH3 - PWM Mode 1
    // =====================================================

    TIM2->CCMR2 |= (6 << 4);
    TIM2->CCMR2 |= (1 << 3);


    // =====================================================
    // CH4 - PWM Mode 1
    // =====================================================

    TIM2->CCMR2 |= (6 << 12);
    TIM2->CCMR2 |= (1 << 11);


    // =====================================================
    // Enable output channels
    // CC1E, CC2E, CC3E, CC4E
    // =====================================================

    TIM2->CCER |= (1 << 0);
    TIM2->CCER |= (1 << 4);
    TIM2->CCER |= (1 << 8);
    TIM2->CCER |= (1 << 12);


    // =====================================================
    // Auto reload preload
    // =====================================================

    TIM2->CR1 |= (1 << 7);


    // =====================================================
    // Update event
    // =====================================================

    TIM2->EGR |= (1 << 0);


    // =====================================================
    // Start timer
    // =====================================================

    TIM2_Start();
}


void TIM2_PWM_SetDuty(uint8_t channel, uint8_t duty)
{
    uint16_t value;

    if (duty > 100)
        duty = 100;

    value = ((TIM2->ARR + 1) * duty) / 100;

    switch (channel)
    {
        case TIM2_CH1:
            TIM2->CCR1 = value;
            break;

        case TIM2_CH2:
            TIM2->CCR2 = value;
            break;

        case TIM2_CH3:
            TIM2->CCR3 = value;
            break;

        case TIM2_CH4:
            TIM2->CCR4 = value;
            break;

        default:
            break;
    }
}


void TIM2_Start(void)
{
    TIM2->CR1 |= (1 << 0);
}


void TIM2_Stop(void)
{
    TIM2->CR1 &= ~(1 << 0);
}